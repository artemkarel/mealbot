"""Сопоставление названий из плана: «Котлеты из индейки «Диетические»» ≈ «Котлеты из индейки на пару».

Нужно, чтобы ссылку из примечания диетолога привязать к позиции плана и к продукту.
Требования жизни: короткая подпись («Сыр», «Мука») не должна цепляться к случайному
товару, а словоформы («муки»/«мука») — считаться разными словами.
"""
import re

# выбрасываем только служебные слова: способ приготовления как раз помогает
# отличить «Отварной язык» от «Язык говяжий» — его оставляем
STOP = {"из", "на", "со", "для", "по", "без", "или", "шт", "гр"}

# окончания, которые режем, чтобы «муки» и «мука» стали одним словом
ENDINGS = ("ыми", "ими", "ами", "ями", "ого", "его", "ых", "их", "ым", "им",
           "ой", "ей", "ый", "ий", "ая", "яя", "ые", "ие", "ов", "ев", "ам", "ям",
           "ах", "ях", "ом", "ем", "у", "ю", "а", "я", "ы", "и", "е", "о")


def stem(w):
    """Снимаем окончание и берём начало слова: «вяленых»/«вялеными» и
    «брускетта»/«брускета» должны стать одним и тем же."""
    for e in ENDINGS:
        if len(w) - len(e) >= 3 and w.endswith(e):
            w = w[:len(w) - len(e)]
            break
    return w[:5]


def words(s):
    """Значимые основы слов: регистр, ё, кавычки и окончания не мешают сравнению."""
    s = (s or "").lower().replace("ё", "е")
    return {stem(w) for w in re.findall(r"[a-zа-я0-9]+", s)
            if len(w) >= 3 and w not in STOP}


def similar(a, b) -> float:
    """0..1 — насколько названия про одно и то же.

    Учитываем обе стороны: «Тофу» входит в «Сырники из тофу с курагой»,
    но это разные вещи — ингредиент не должен наследовать ссылку на готовое блюдо.
    """
    wa, wb = words(a), words(b)
    if not wa or not wb:
        return 0.0
    return 2 * len(wa & wb) / (len(wa) + len(wb))


def best(label, candidates, key=lambda x: x, threshold=0.6):
    """Лучший кандидат для подписи ссылки или None.

    Совпадение по одному-единственному слову засчитываем только если это
    практически всё название с обеих сторон — иначе «Сыр» прилипнет к первому
    попавшемуся сыру, а «Мука» — к любой муке.
    """
    wl = words(label)
    if not wl:
        return None
    scored = []
    for c in candidates:
        wc = words(key(c))
        if not wc:
            continue
        common = wl & wc
        if not common:
            continue
        sc = 2 * len(common) / (len(wl) + len(wc))
        if len(common) == 1 and (len(wl) > 1 or len(wc) > 1):
            continue                     # одно общее слово — это ещё не тот же товар
        # короткая подпись («Сыр», «Мука») подходит слишком многим — требуем почти точного
        if sc >= (0.8 if len(wl) == 1 else threshold):
            scored.append((sc, len(common), c))
    if not scored:
        return None
    scored.sort(key=lambda x: (-x[0], -x[1]))
    if len(scored) > 1 and scored[0][0] == scored[1][0]:
        return None                      # два одинаково похожих товара — лучше не гадать
    return scored[0][2]
